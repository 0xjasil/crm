import type { FastifyPluginAsync } from 'fastify';
import { authenticate } from '../../middleware/auth.middleware.js';
import { AdmissionActionsRoutes } from './admission-actions.routes.js';
import { CallLogRoutes } from './call-log.routes.js';
import { DataManagementRoutes } from './data-management.routes.js';
import { EnquiryActionRoutes } from './enquiry-action.routes.js';
import { EnquiryActivityActionsRoutes } from './enquiry-activity-actions.routes.js';
import { EnquiryStatusActionsRoutes } from './enquiry-status-actions.routes.js';
import { EnquiryRoutes } from './enquiry.routes.js';
import { ExpenseActionsRoutes } from './expense-actions.routes.js';
import { FeeCollectionActionsRoutes } from './fee-collection-actions.routes.js';
import { FollowUpRoutes } from './follow-up.routes.js';
import { InvoiceActionsRoutes } from './invoice-actions.routes.js';
import { InvoiceCatalogActionsRoutes } from './invoice-catalog-actions.routes.js';
import { JobOrderRoutes } from './job-order.routes.js';
import { NotificationRoutes } from './notification.routes.js';
import { ProposalProposalActionsRoutes } from './proposal-proposal-actions.routes.js';
import { ReceiptActionsRoutes } from './receipt-actions.routes.js';
import { ReportActionsRoutes } from './report-actions.routes.js';
import { ServiceActionsRoutes } from './service-actions.routes.js';
import { AuthRoutes } from './auth.routes.js';
import { DashboardRoutes } from './dashboard.routes.js';
import { ReportsRoutes } from './reports.routes.js';
export const workflowRoutes: FastifyPluginAsync = async (app) => {
    app.addHook('preHandler', authenticate);
    app.addHook('preSerialization', async (_request, _reply, payload) => {
        // Relation queries must never expose stored credentials in an API response.
        return JSON.parse(JSON.stringify(payload, (key, value) => ['password', 'accessToken', 'refreshToken', 'idToken'].includes(key) ? undefined : value));
    });
    await app.register(AdmissionActionsRoutes, { prefix: '/admission-actions' });
    await app.register(CallLogRoutes, { prefix: '/call-log' });
    await app.register(DataManagementRoutes, { prefix: '/data-management' });
    await app.register(EnquiryActionRoutes, { prefix: '/enquiry-action' });
    await app.register(EnquiryActivityActionsRoutes, { prefix: '/enquiry-activity-actions' });
    await app.register(EnquiryStatusActionsRoutes, { prefix: '/enquiry-status-actions' });
    await app.register(EnquiryRoutes, { prefix: '/enquiry' });
    await app.register(ExpenseActionsRoutes, { prefix: '/expense-actions' });
    await app.register(FeeCollectionActionsRoutes, { prefix: '/fee-collection-actions' });
    await app.register(FollowUpRoutes, { prefix: '/follow-up' });
    await app.register(InvoiceActionsRoutes, { prefix: '/invoice-actions' });
    await app.register(InvoiceCatalogActionsRoutes, { prefix: '/invoice-catalog-actions' });
    await app.register(JobOrderRoutes, { prefix: '/job-order' });
    await app.register(NotificationRoutes, { prefix: '/notification' });
    await app.register(ProposalProposalActionsRoutes, { prefix: '/proposal-proposal-actions' });
    await app.register(ReceiptActionsRoutes, { prefix: '/receipt-actions' });
    await app.register(ReportActionsRoutes, { prefix: '/report-actions' });
    await app.register(ServiceActionsRoutes, { prefix: '/service-actions' });
    await app.register(AuthRoutes, { prefix: '/auth' });
    await app.register(DashboardRoutes, { prefix: '/dashboard' });
    await app.register(ReportsRoutes, { prefix: '/reports' });
};
